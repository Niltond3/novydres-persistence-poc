#!/usr/bin/env node
/** MW-013 FIS-04 finalized noncanonical integration gate; also run validar-malha-territorial-fis04.mjs for full topology. */
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {dirname,join} from 'node:path';
import {fileURLToPath} from 'node:url';
const root=dirname(fileURLToPath(import.meta.url));
const textFile=n=>readFileSync(join(root,n),'utf8');
const read=n=>{const buf=readFileSync(join(root,n));return {doc:JSON.parse(buf.toString('utf8')),sha:createHash('sha1').update(Buffer.concat([Buffer.from('blob '+buf.length+'\0'),buf])).digest('hex')}};
const e=read('macroermos-2010.proposal.json').doc;
const b=read('malha-territorial-ermos-fis04-2010.refined.proposal.json');
const c=read('macrogeometria-litoral-baia-ilhas-2010.proposal.json');
const r=read('macrorelevo-2010.proposal.json');
const h=read('macrohidrografia-2010.proposal.json');
const html=textFile('visualizador-fisico-2010.html');
assert.equal(e.subject_id,'world-atlas-novydres');
assert.equal(e.year,2010);
assert.equal(e.approval.workflow,'OWNER_APPROVED_NONCANONICAL_WORKING_BASELINE_CLOSED_FOR_SCOPE');
assert.equal(e.approval.canonical_status,'NOT_APPROVED');
assert.equal(e.approval.geometry_authority,'OWNER_APPROVED_NONCANONICAL_WORKING_BASELINE');
assert.equal(e.approval.owner_approval_for_this_geometry.decision,'APPROVED_FIS04_SCOPE_CLOSED_NONCANONICAL_WORKING_BASELINE');
assert.equal(b.doc.approval.owner_approval_for_final_scope.decision,'APPROVED_FIS04_SCOPE_CLOSED_NONCANONICAL_WORKING_BASELINE');
assert.equal(b.doc.approval.canonical_status,'NOT_APPROVED');
assert.equal(e.wilderness_model.geometry_source,'malha-territorial-ermos-fis04-2010.refined.proposal.json');
assert.equal(e.wilderness_model.geometry_source_blob_sha,b.sha);
assert.deepEqual(e.wilderness_model.corridor_segments,b.doc.geometry.segments);
assert.equal(e.wilderness_model.corridor_segments.length,10);
assert.equal(e.validation_summary.candidate_polygon_vertex_count,2349);
assert.equal(e.provenance.candidate_coast_blob_sha,c.sha);
assert.equal(e.provenance.candidate_relief_blob_sha,r.sha);
assert.equal(e.provenance.candidate_hydro_blob_sha,h.sha);
for(const x of [c,r,h])assert.equal(x.doc.approval.canonical_status,'NOT_APPROVED');
assert.equal(e.wilderness_model.natural_special_zone_not_raion,true);
assert.equal(e.wilderness_model.number_of_raions_in_canon,9);
assert.equal(e.spatial_reference.crs,'NOVYDRES-LOCAL-2010');
assert.equal(e.spatial_reference.geodetic_anchor,null);
assert.equal(e.spatial_reference.municipal_boundary,null);
const match=html.match(/<script id="geometry-data" type="text\/plain">([\s\S]*?)<\/script>/);
assert(match,'Main viewer data not found');
const records=match[1].trim().split(/\r?\n/).filter(Boolean).map(s=>{const [layer,id,kind,label,group,coordinates]=s.split('|');return{layer,id,kind,label,group,points:coordinates.split(';').map(pair=>pair.split(',').map(Number))}});
assert.equal(records.length,41);
const count=k=>records.filter(r=>r.layer===k).length;
assert.equal(count('ermos'),10);
assert.equal(count('islands'),3);
assert.equal(count('watercourses'),9);
assert.equal(count('waterbodies'),3);
assert.equal(count('relief'),7);
assert.equal(count('crests'),3);
assert.equal(count('basins'),5);
for(const f of b.doc.geometry.segments)assert.deepEqual(records.find(x=>x.id===f.id)?.points,f.ring_xy_m,'Main viewer ermo mismatch '+f.id);
assert(html.includes("ANTES / DEPOIS de MW-013"),'Before/after comparison link missing');
console.log('MW-013 FIS-04 INTEGRATION PASS — 41 full-viewer features, 10 Ermo polygons, 2349 vertices, noncanonical closure');
